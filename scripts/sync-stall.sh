#!/usr/bin/env bash
# sync-stall.sh — keep the freeze-aware wait helper (stall.go) identical everywhere.
#
# The target modules are separate and air-gapped, so each carries its own copy of the
# stall monitor (Wait / EffectiveElapsed / FUZZ_STALL_LOG). shared/stall.go.body is the
# single canonical body; this script writes it into every targets/<module>/stall_test.go
# (package line taken from the module's own test files) and, with --check, FAILS if any
# copy differs — so the copies cannot drift silently.
#
#   scripts/sync-stall.sh                 regenerate every targets/*/stall_test.go
#   scripts/sync-stall.sh --check         verify them (CI / scripts/check.sh)
#   scripts/sync-stall.sh --check FILE... also verify external copies (e.g. keyorix
#                                         internal/fuzzutil/stall.go, dashdiag's): they
#                                         must equal the canonical body after their
#                                         `package` line; any header above it is ignored.
#
# Canonical source of the logic: keyorixhq/keyorix internal/fuzzutil/stall.go.
set -euo pipefail
cd "$(dirname "$0")/.."

BODY=shared/stall.go.body
MODE=write
if [ "${1:-}" = "--check" ]; then MODE=check; shift; fi
[ -f "$BODY" ] || { echo "sync-stall: $BODY missing" >&2; exit 2; }

fail=0
body_after_package() { awk 'f{print} /^package /{f=1}' "$1"; }

for gomod in targets/*/go.mod; do
	mod="$(dirname "$gomod")"
	pkg="$(grep -h '^package ' "$mod"/*_test.go 2>/dev/null | grep -v '^package stall$' | head -1 | awk '{print $2}')"
	[ -n "$pkg" ] || continue   # module without tests: nothing to sync
	out="$mod/stall_test.go"
	want="$(mktemp)"
	{
		echo "// Code generated by scripts/sync-stall.sh from shared/stall.go.body; DO NOT EDIT."
		echo "package $pkg"
		cat "$BODY"
	} >"$want"
	if [ "$MODE" = write ]; then
		cp "$want" "$out"; echo "wrote $out"
	elif ! cmp -s "$want" "$out"; then
		echo "FAIL  $out differs from shared/stall.go.body (run scripts/sync-stall.sh)"; fail=1
	else
		echo "ok    $out"
	fi
	rm -f "$want"
done

if [ "$MODE" = check ]; then
	for ext in "$@"; do
		if [ ! -f "$ext" ]; then echo "FAIL  $ext not found"; fail=1; continue; fi
		if cmp -s <(body_after_package "$ext") "$BODY"; then echo "ok    $ext"; else
			echo "FAIL  $ext differs from shared/stall.go.body after its package line"; fail=1
		fi
	done
fi
exit "$fail"
